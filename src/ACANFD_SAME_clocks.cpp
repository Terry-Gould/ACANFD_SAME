#include <ACANFD_SAME_clocks.h>
#include <Arduino.h> // For REG_OSCCTRL_DPLLRATIO1

//----------------------------------------------------------------------------------------
//   Get CPU clock frequency (in Hz)
//----------------------------------------------------------------------------------------

uint32_t CPUClockFrequency (void) {
  return F_CPU ;
}

//----------------------------------------------------------------------------------------
//   Get DPLL1 clock frequency (in Hz)
//----------------------------------------------------------------------------------------

uint32_t DPPL1ClockFrequency (void) {
  uint32_t frequencyMHz = (REG_OSCCTRL_DPLLRATIO1 & 255) + 1 ;
  return frequencyMHz * 1000 * 1000 ;
}

